"""Build the CloudFront Function (viewer request) for flik.co.id on AWS from _redirects.

Run from the site root after changing _redirects:

    python3 scripts/build_cf_function.py

It writes scripts/cloudfront-function.js. Paste that file into
CloudFront > Functions > flik-landing-router (runtime cloudfront-js-2.0) and publish,
or let the GitHub Action do it (see .github/AWS-SETUP.md).

What the function does, in order:
  1. www.flik.co.id  ->  https://flik.co.id (301), keeping path and query
  2. exact redirects from _redirects (old flik.co.id addresses, hidden pages, login/register)
  3. prefix redirects from _redirects (lines whose source ends in /*, e.g. /en/*)
  4. /about  ->  /about/ (301), the same trailing-slash rule as Vercel and Cloudflare
  5. /about/ ->  serves about/index.html from S3
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
exact, prefix = {}, []
for line in open(os.path.join(ROOT, '_redirects')):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    src, dst, code = line.split()[:3]
    if src.endswith('/*'):
        prefix.append([src[:-1], dst, int(code)])   # '/en/*' -> prefix '/en/'
    else:
        exact[src] = [dst, int(code)]

js = """// Generated by scripts/build_cf_function.py from _redirects. Do not edit by hand.
// CloudFront Function (cloudfront-js-2.0), viewer request, for flik.co.id.
var MAIN_HOST = 'flik.co.id';
var EXACT = %s;
var PREFIX = %s;

function qs(q) {
  var parts = [];
  for (var k in q) {
    var v = q[k];
    if (v.multiValue) { v.multiValue.forEach(function (m) { parts.push(k + (m.value ? '=' + m.value : '')); }); }
    else { parts.push(k + (v.value ? '=' + v.value : '')); }
  }
  return parts.length ? '?' + parts.join('&') : '';
}

function go(code, location) {
  return { statusCode: code, statusDescription: code === 301 ? 'Moved Permanently' : 'Found',
           headers: { location: { value: location }, 'cache-control': { value: 'public, max-age=300' } } };
}

function handler(event) {
  var req = event.request;
  var host = req.headers.host ? req.headers.host.value : '';
  var uri = req.uri;
  var q = qs(req.querystring);

  // 1. www to the main address
  if (host === 'www.' + MAIN_HOST) return go(301, 'https://' + MAIN_HOST + uri + q);

  // 2. exact redirects
  var r = EXACT[uri];
  if (r) return go(r[1], r[0]);

  // 3. prefix redirects (:splat is the rest of the path)
  for (var i = 0; i < PREFIX.length; i++) {
    var p = PREFIX[i];
    if (uri.indexOf(p[0]) === 0) return go(p[2], p[1].replace(':splat', uri.slice(p[0].length)) + q);
  }

  // 4. folders without a trailing slash get one
  var last = uri.slice(uri.lastIndexOf('/') + 1);
  if (last && last.indexOf('.') === -1) return go(301, uri + '/' + q);

  // 5. folders serve their index.html
  if (uri.charAt(uri.length - 1) === '/') req.uri = uri + 'index.html';
  return req;
}
""" % (json.dumps(exact, indent=0), json.dumps(prefix))

out = os.path.join(ROOT, 'scripts', 'cloudfront-function.js')
open(out, 'w').write(js)
print('wrote scripts/cloudfront-function.js:', len(exact), 'exact,', len(prefix), 'prefix redirects,', len(js.encode()), 'bytes (CloudFront limit 10240)')
