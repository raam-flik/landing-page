"""Build the pages that come from data, plus sitemap.xml.

Run from the site root after you add or change a blog post (POSTS in blog/index.html),
a customer (CUSTOMERS / STORIES in customers/story/index.html), or any page:

    python3 scripts/build_pages.py

It writes:
  - blog/<slug>/index.html       one page per post, from blog/index.html
  - customers/<slug>/index.html  one page per brand, from customers/story/index.html
  - assets/blog/<img>-og.jpg     1200x630 share image per post (only if missing)
  - sitemap.xml                  every public page

Never edit the generated pages by hand: change the template (blog/index.html or
customers/story/index.html) and run this again.
"""
import glob, html, json, os, re, subprocess, sys
from datetime import date

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT_DIR)
SITE = 'https://flik.co.id'
OG_DEFAULT = SITE + '/assets/og/flik-og.jpg'
GEN = '<!-- Generated by scripts/build_pages.py from {src}. Edit that file, then run the script again. -->\n'
# pages kept out of the sitemap (sign-in screens, the story template, copies of the dashboard)
NOT_IN_SITEMAP = {'login/', 'register/', 'customers/story/'}


def esc(t):
    return html.escape(html.unescape(t), quote=True)


def set_head(s, title, desc, canon, image=OG_DEFAULT, og_type='website'):
    s = re.sub(r'<title>[^<]*</title>', f'<title>{esc(title)}</title>', s, count=1)
    s = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{esc(desc)}">', s, count=1)
    s = re.sub(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{canon}">', s, count=1)
    for prop, val in (('og:type', og_type), ('og:title', title), ('og:description', desc), ('og:url', canon), ('og:image', image)):
        s = re.sub(rf'<meta property="{prop}" content="[^"]*">', f'<meta property="{prop}" content="{esc(val)}">', s, count=1)
    for name, val in (('twitter:title', title), ('twitter:description', desc), ('twitter:image', image)):
        s = re.sub(rf'<meta name="{name}" content="[^"]*">', f'<meta name="{name}" content="{esc(val)}">', s, count=1)
    return s


def one_level_deeper(s):
    """blog/index.html sits one folder up from blog/<slug>/: every ../ becomes ../../"""
    return re.sub(r'(["\'(])\.\./', r'\1../../', s)


def write(path, s):
    if os.path.dirname(path): os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != s:
        open(path, 'w').write(s)
        return True
    return False


def clear_generated(folder, keep):
    """remove generated pages whose post or brand no longer exists"""
    for f in glob.glob(f'{folder}/*/index.html'):
        slug = f.split('/')[-2]
        if slug not in keep and open(f).read().startswith('<!doctype html>\n<!-- Generated by scripts/build_pages.py'):
            os.remove(f); os.rmdir(os.path.dirname(f)); print('removed', f)


# ---------- blog ----------
def build_blog():
    tpl = open('blog/index.html').read()
    m = re.search(r'const POSTS=(\[.*?\]);\n', tpl, re.S)
    posts = json.loads(m.group(1))
    # the list view and its H1 stay on blog/ only; each post page has one H1, the article title
    body = re.sub(r'<!-- ===== List view.*?(?=<!-- ===== Article view)', '', tpl, count=1, flags=re.S)
    body = body.replace('<div data-view="post" hidden>', '<div data-view="post">', 1)
    body = one_level_deeper(body)
    made = []
    for p in posts:
        slug = p['slug']
        img = p.get('img')
        image = OG_DEFAULT
        if img:
            og = f'assets/blog/{img}-og.jpg'
            if not os.path.exists(og):
                from PIL import Image
                im = Image.open(f'assets/blog/{img}-l.jpg').convert('RGB')
                w, h = im.size
                im = im.resize((1200, round(h * 1200 / w)), Image.LANCZOS)
                top = max(0, (im.size[1] - 630) // 2)
                im.crop((0, top, 1200, top + 630)).save(og, quality=85, optimize=True)
            image = f'{SITE}/{og}'
        canon = f'{SITE}/blog/{slug}/'
        s = set_head(body, f"{p['title']} | FLIK Blog", p['desc'], canon, image, 'article')
        ld = {"@context": "https://schema.org", "@type": "Article", "headline": p['title'], "description": p['desc'],
              "datePublished": p['iso'], "image": image, "mainEntityOfPage": canon,
              "author": {"@type": "Organization", "name": "FLIK", "url": SITE + '/'},
              "publisher": {"@type": "Organization", "name": "FLIK", "url": SITE + '/', "logo": {"@type": "ImageObject", "url": SITE + '/apple-touch-icon.png'}}}
        s = re.sub(r'<script type="application/ld\+json">.*?</script>',
                   lambda _: '<script type="application/ld+json">\n' + json.dumps(ld, ensure_ascii=False).replace('</', '<\\/') + '\n</script>', s, count=1, flags=re.S)
        s = s.replace('</head>', f'<script>window.PAGE_POST={json.dumps(slug)};</script>\n</head>', 1)
        cover = (f'<span class="cov cov-ph" data-bg="../../assets/blog/{img}-l.webp?v=3" role="img" aria-label="{esc(p["title"])}"></span>' if img else '')
        art = (f'<a href="../" class="art-back">All articles</a><h1>{p["title"]}</h1>'
               f'<span class="bm"><span>{p["date"]}</span><i></i><span>{p["min"]} min read</span></span>{cover}'
               f'<div class="art-body">{p["html"]}</div>')
        s = s.replace('<article class="art" id="art"></article>', f'<article class="art" id="art">{art}</article>', 1)
        s = s.replace('<!doctype html>\n', '<!doctype html>\n' + GEN.format(src='blog/index.html'), 1)
        if write(f'blog/{slug}/index.html', s): print('wrote', f'blog/{slug}/')
        made.append(f'blog/{slug}/')
    clear_generated('blog', {p['slug'] for p in posts})
    return made


# ---------- customer stories ----------
def build_stories():
    tpl = open('customers/story/index.html').read()
    i = tpl.index('const CUSTOMERS=['); j = tpl.index('\n', tpl.index('const storyHead='))
    js = tpl[i:j] + "\nprocess.stdout.write(JSON.stringify(CUSTOMERS.map(c=>({slug:c.slug,name:c.name,head:storyHead(c),intro:STORIES[c.slug]?(STORIES[c.slug].p?Object.values(STORIES[c.slug].p)[0][1]:STORIES[c.slug].i):''}))))"
    customers = json.loads(subprocess.run(['node', '-e', js], capture_output=True, text=True, check=True).stdout)
    base = tpl.replace('<meta name="robots" content="noindex">\n', '', 1)
    made = []
    for c in customers:
        slug = c['slug']
        canon = f'{SITE}/customers/{slug}/'
        head = re.sub(r'<[^>]+>', '', c['head'])
        if head and head[-1] not in '.!?': head += '.'
        desc = (head + ' ' + re.sub(r'<[^>]+>', '', c['intro'])).strip()
        if len(desc) > 160: desc = desc[:157].rsplit(' ', 1)[0] + '…'
        s = set_head(base, f"{c['name']} customer story | FLIK", desc, canon)
        s = s.replace('</head>', f'<script>window.PAGE_STORY={json.dumps(slug)};</script>\n</head>', 1)
        s = s.replace('<span id="cs-crumb"></span>', f'<span id="cs-crumb">{esc(c["name"])}</span>', 1)
        s = s.replace('<!doctype html>\n', '<!doctype html>\n' + GEN.format(src='customers/story/index.html'), 1)
        if write(f'customers/{slug}/index.html', s): print('wrote', f'customers/{slug}/')
        made.append(f'customers/{slug}/')
    clear_generated('customers', {c['slug'] for c in customers} | {'story'})
    return made


# ---------- sitemap ----------
def lastmod(path):
    out = subprocess.run(['git', 'log', '-1', '--format=%cs', '--', path], capture_output=True, text=True).stdout.strip()
    return out or date.today().isoformat()


def build_sitemap():
    urls = []
    for f in sorted(glob.glob('**/index.html', recursive=True)):
        if f.startswith(('archive/', 'dashboard/', 'scripts/', 'assets/')): continue
        path = '' if f == 'index.html' else f[:-len('index.html')]
        if path in NOT_IN_SITEMAP: continue
        if 'name="robots" content="noindex' in open(f).read(): continue
        urls.append((path, lastmod(f)))
    # home first, then by path
    urls.sort(key=lambda u: (u[0] != '', u[0]))
    xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for path, mod in urls:
        xml.append(f'  <url><loc>{SITE}/{path}</loc><lastmod>{mod}</lastmod></url>')
    xml.append('</urlset>\n')
    if write('sitemap.xml', '\n'.join(xml)): print('wrote sitemap.xml')
    print(len(urls), 'URLs in sitemap.xml')


if __name__ == '__main__':
    build_blog()
    build_stories()
    build_sitemap()
